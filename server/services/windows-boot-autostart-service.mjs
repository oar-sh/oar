import fs from 'fs';
import path from 'path';
import { execFile, spawn } from 'child_process';

import { resolveOarRoot } from './oar-state-migration-service.mjs';
import {
  LEGACY_WINDOWS_AUTOSTART_FILENAME,
  WINDOWS_AUTOSTART_FILENAME,
  escapeBatchValue,
  resolveWindowsStartupDirectory,
} from './windows-autostart-service.mjs';

/**
 * "At system startup" autostart: a boot-trigger Scheduled Task running the
 * relay as the current user via S4U ("run whether user is logged on or not",
 * no stored password), headless, reachable before anyone signs in.
 *
 * The task's settings are a verbatim port of the hand-made task this design
 * was proven on (docs/plans/2026-09-02-windows-boot-autostart.md): boot
 * trigger +30s, no execution time limit, restart 5x/1min, StartWhenAvailable,
 * IgnoreNew. The task executes a generated launcher .cmd rather than node
 * directly, so a config-path change only regenerates a file — it never needs
 * the task re-registered (which would mean another elevation).
 *
 * Elevation is THE constraint here: registering or deleting a boot-trigger
 * task needs administrator rights and the relay runs unelevated. enable() and
 * disable() therefore spawn `Start-Process -Verb RunAs` around a generated
 * sweep script; the UAC prompt renders on the PC's physical desktop only, so
 * both report `pendingElevation` and the caller polls getState() until the
 * task appears/disappears (or shows `manualCommand` after a decline/timeout).
 * The elevated script does nothing but the schtasks calls — every file write
 * and cleanup stays in this unelevated process.
 */

export const BOOT_TASK_NAME = 'oar-relay';
// The hand-made pre-rebrand task. Recognized so the UI can offer migration,
// and deleted inside the same elevated sweep that registers the new name —
// one UAC covers the whole transition.
export const LEGACY_BOOT_TASK_NAME = 'copilot-remote-relay';
export const BOOT_LAUNCHER_FILENAME = 'oar-web-relay-launcher.cmd';
export const BOOT_TASK_XML_FILENAME = 'oar-relay-task.xml';
export const BOOT_ELEVATION_SCRIPT_FILENAME = 'oar-relay-elevate.ps1';
const ELEVATION_TIMEOUT_MS = 120_000;

function normalizeText(value) {
  return String(value == null ? '' : value).trim();
}

function escapeXml(value) {
  return String(value == null ? '' : value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

/**
 * The launcher the task executes. Same shape as the sign-in .cmd minus the
 * `title` line: a boot task runs in session 0 where no console is ever shown.
 */
export function buildBootLauncherScript({
  packageRoot,
  nodePath = process.execPath,
  configPath = '',
  pathImpl = path,
} = {}) {
  if (!normalizeText(packageRoot)) {
    throw new Error('Windows boot autostart requires the package root.');
  }
  if (!normalizeText(nodePath)) {
    throw new Error('Windows boot autostart requires the Node.js executable path.');
  }
  const resolvedPackageRoot = pathImpl.resolve(String(packageRoot));
  const serverPath = pathImpl.join(resolvedPackageRoot, 'server', 'server.js');
  const lines = [
    '@echo off',
    'rem Generated by OAR settings (system-startup autostart). Regenerated on',
    'rem every settings change - do not edit by hand.',
  ];
  if (normalizeText(configPath)) {
    lines.push(`set "COPILOT_WEB_RELAY_CONFIG=${escapeBatchValue(pathImpl.resolve(configPath))}"`);
  }
  lines.push(
    `cd /d "${escapeBatchValue(resolvedPackageRoot)}"`,
    `"${escapeBatchValue(pathImpl.resolve(nodePath))}" "${escapeBatchValue(serverPath)}"`,
    '',
  );
  return lines.join('\r\n');
}

/**
 * Task Scheduler XML, settings ported verbatim from the proven manual task.
 * The S4U principal is registered by SID, not account name: a by-name
 * principal breaks if the user is renamed, a SID does not.
 */
export function buildBootTaskXml({
  sid,
  launcherPath,
  packageRoot,
  description = 'Starts the OAR web relay at system startup (S4U, no logon required). Managed by OAR settings.',
} = {}) {
  if (!/^S-1-[\d-]+$/.test(normalizeText(sid))) {
    throw new Error(`Windows boot autostart requires the current user's SID (got: ${JSON.stringify(sid)}).`);
  }
  if (!normalizeText(launcherPath)) {
    throw new Error('Windows boot autostart requires the launcher path.');
  }
  if (!normalizeText(packageRoot)) {
    throw new Error('Windows boot autostart requires the package root.');
  }
  return [
    '<?xml version="1.0" encoding="UTF-16"?>',
    '<Task version="1.3" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">',
    '  <RegistrationInfo>',
    `    <Description>${escapeXml(description)}</Description>`,
    `    <URI>\\${BOOT_TASK_NAME}</URI>`,
    '  </RegistrationInfo>',
    '  <Principals>',
    '    <Principal id="Author">',
    `      <UserId>${escapeXml(normalizeText(sid))}</UserId>`,
    '      <LogonType>S4U</LogonType>',
    '    </Principal>',
    '  </Principals>',
    '  <Settings>',
    '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>',
    '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>',
    '    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>',
    '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>',
    '    <RestartOnFailure>',
    '      <Count>5</Count>',
    '      <Interval>PT1M</Interval>',
    '    </RestartOnFailure>',
    '    <StartWhenAvailable>true</StartWhenAvailable>',
    '    <UseUnifiedSchedulingEngine>true</UseUnifiedSchedulingEngine>',
    '  </Settings>',
    '  <Triggers>',
    '    <BootTrigger>',
    '      <Delay>PT30S</Delay>',
    '    </BootTrigger>',
    '  </Triggers>',
    '  <Actions Context="Author">',
    '    <Exec>',
    '      <Command>C:\\Windows\\System32\\cmd.exe</Command>',
    `      <Arguments>/d /c "${escapeXml(launcherPath)}"</Arguments>`,
    `      <WorkingDirectory>${escapeXml(packageRoot)}</WorkingDirectory>`,
    '    </Exec>',
    '  </Actions>',
    '</Task>',
    '',
  ].join('\r\n');
}

/**
 * schtasks rejects a UTF-8 file whose XML header declares UTF-16 (and the
 * header must declare UTF-16 for /create /xml) — so the bytes on disk are
 * UTF-16LE with a BOM, matching what `schtasks /query /xml` itself exports.
 */
export function encodeTaskXml(xml) {
  return Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(String(xml), 'utf16le')]);
}

/** Minimal field scrape of a task's exported XML; no XML parser dependency. */
export function parseTaskXml(xmlText) {
  const text = String(xmlText == null ? '' : xmlText);
  const grab = (tag) => {
    const match = text.match(new RegExp(`<${tag}>([^<]*)</${tag}>`));
    return match ? match[1].trim() : null;
  };
  return {
    command: grab('Command'),
    argumentsLine: grab('Arguments'),
    workingDirectory: grab('WorkingDirectory'),
    logonType: grab('LogonType'),
    userId: grab('UserId'),
  };
}

/**
 * Ours or someone else's? A task counts as ours when its action runs our
 * launcher path; anything else under our name is `foreign` and the UI offers
 * an explicit "Replace", never a silent overwrite.
 */
export function classifyTaskXml(xmlText, { launcherPath } = {}) {
  const parsed = parseTaskXml(xmlText);
  const needle = normalizeText(launcherPath).toLowerCase();
  if (needle && String(parsed.argumentsLine || '').toLowerCase().includes(needle)) {
    return 'ready';
  }
  return 'foreign';
}

/**
 * The elevated sweep. Everything the admin token is actually needed for —
 * and nothing else — in one script, so one UAC covers the whole transition
 * out of any mixed state (legacy-named task, hand-made task, fresh install).
 */
export function buildElevationScript({ action, xmlPath } = {}) {
  if (action === 'enable') {
    if (!normalizeText(xmlPath)) {
      throw new Error('The enable sweep needs the task XML path.');
    }
    return [
      `schtasks /delete /tn "${LEGACY_BOOT_TASK_NAME}" /f 2>$null`,
      `schtasks /delete /tn "${BOOT_TASK_NAME}" /f 2>$null`,
      `schtasks /create /tn "${BOOT_TASK_NAME}" /xml "${xmlPath}"`,
      'exit $LASTEXITCODE',
      '',
    ].join('\r\n');
  }
  if (action === 'disable') {
    return [
      `schtasks /delete /tn "${BOOT_TASK_NAME}" /f 2>$null`,
      `schtasks /delete /tn "${LEGACY_BOOT_TASK_NAME}" /f 2>$null`,
      'exit 0',
      '',
    ].join('\r\n');
  }
  throw new Error(`Unknown elevation action: ${JSON.stringify(action)}`);
}

/** `whoami /user /fo csv` → the current user's SID. */
export function parseSidFromWhoami(stdout) {
  const match = String(stdout || '').match(/"(S-1-[\d-]+)"/);
  return match ? match[1] : null;
}

function defaultExecFileImpl(file, args) {
  return new Promise((resolve) => {
    execFile(file, args, { windowsHide: true }, (error, stdout, stderr) => {
      resolve({
        code: error ? (typeof error.code === 'number' ? error.code : 1) : 0,
        stdout: String(stdout || ''),
        stderr: String(stderr || ''),
      });
    });
  });
}

export function createWindowsBootAutostartService({
  platform = process.platform,
  env = process.env,
  packageRoot,
  nodePath = process.execPath,
  configPath = '',
  fsImpl = fs,
  pathImpl = path,
  execFileImpl = defaultExecFileImpl,
  spawnImpl = spawn,
  setTimeoutImpl = setTimeout,
  clearTimeoutImpl = clearTimeout,
  now = () => Date.now(),
  logger = console,
} = {}) {
  const supported = platform === 'win32';
  // One elevation in flight at a time; getState() reports it and the
  // completion callback resolves it.
  let pending = null; // { action, startedAt, timer, child }
  let lastError = null;

  const oarRoot = () => resolveOarRoot(env, platform);
  const launcherPath = () => pathImpl.join(oarRoot(), BOOT_LAUNCHER_FILENAME);
  const xmlPath = () => pathImpl.join(oarRoot(), BOOT_TASK_XML_FILENAME);
  const elevationScriptPath = () => pathImpl.join(oarRoot(), BOOT_ELEVATION_SCRIPT_FILENAME);

  function log(message) {
    try { logger?.log?.(`[boot-autostart] ${message}`); } catch {}
  }

  async function queryTaskXml(taskName) {
    const result = await execFileImpl('schtasks', ['/query', '/tn', taskName, '/xml']);
    return result.code === 0 ? result.stdout : null;
  }

  function startupCmdPaths() {
    const dir = resolveWindowsStartupDirectory(env, pathImpl);
    return [
      pathImpl.join(dir, WINDOWS_AUTOSTART_FILENAME),
      pathImpl.join(dir, LEGACY_WINDOWS_AUTOSTART_FILENAME),
    ];
  }

  function removeStartupCmds() {
    let removed = 0;
    for (const target of startupCmdPaths()) {
      try {
        if (fsImpl.existsSync(target)) {
          fsImpl.unlinkSync(target);
          removed += 1;
        }
      } catch (error) {
        log(`could not remove ${target}: ${error?.message || error}`);
      }
    }
    return removed;
  }

  function manualCommandFor(action) {
    return action === 'disable'
      ? `schtasks /delete /tn "${BOOT_TASK_NAME}" /f`
      : `schtasks /create /tn "${BOOT_TASK_NAME}" /xml "${xmlPath()}" /f`;
  }

  function spawnsDisabled() {
    // The e2e harness's kill switch. schtasks is not a provider CLI, but the
    // point is identical: an isolated relay must not read (let alone mutate)
    // host machine state.
    return Boolean(normalizeText(env?.COPILOT_WEB_RELAY_DISABLE_CLI_SPAWN));
  }

  async function getState() {
    if (!supported) {
      return { supported: false, platform };
    }
    if (spawnsDisabled()) {
      return {
        supported: true,
        platform,
        taskStatus: 'unknown',
        taskName: BOOT_TASK_NAME,
        legacyTaskPresent: false,
        launcherPath: null,
        pendingElevation: null,
        lastError: null,
        manualCommand: manualCommandFor('enable'),
      };
    }
    const ownXml = await queryTaskXml(BOOT_TASK_NAME);
    const legacyXml = await queryTaskXml(LEGACY_BOOT_TASK_NAME);
    const taskStatus = ownXml === null
      ? (legacyXml !== null ? 'legacy' : 'missing')
      : classifyTaskXml(ownXml, { launcherPath: launcherPath() });
    return {
      supported: true,
      platform,
      taskStatus,
      taskName: BOOT_TASK_NAME,
      legacyTaskPresent: legacyXml !== null,
      launcherPath: fsImpl.existsSync(launcherPath()) ? launcherPath() : null,
      pendingElevation: pending ? pending.action : null,
      lastError,
      manualCommand: manualCommandFor(pending?.action || 'enable'),
    };
  }

  function writeFileAtomic(targetPath, contents) {
    fsImpl.mkdirSync(pathImpl.dirname(targetPath), { recursive: true });
    const temporaryPath = `${targetPath}.tmp`;
    fsImpl.writeFileSync(temporaryPath, contents);
    fsImpl.renameSync(temporaryPath, targetPath);
  }

  function settlePending(outcome) {
    if (!pending) return;
    if (pending.timer) clearTimeoutImpl(pending.timer);
    pending = null;
    lastError = outcome || null;
  }

  /**
   * The elevated child is powershell running Start-Process -Verb RunAs -Wait:
   * the outer process lives exactly as long as the UAC prompt plus the sweep
   * script, so its exit is the "elevation finished (or was declined)" signal.
   */
  function spawnElevated(action, onSettled) {
    const child = spawnImpl('powershell.exe', [
      '-NoProfile',
      '-NonInteractive',
      '-Command',
      [
        '$p = Start-Process -FilePath powershell.exe -Verb RunAs -Wait -PassThru -WindowStyle Hidden -ArgumentList',
        `'-NoProfile','-ExecutionPolicy','Bypass','-File','${elevationScriptPath()}'`,
        '; exit $p.ExitCode',
      ].join(' '),
    ], {
      stdio: ['ignore', 'ignore', 'pipe'],
      windowsHide: true,
    });
    let stderr = '';
    child.stderr?.on?.('data', (chunk) => { stderr = `${stderr}${chunk}`.slice(-2000); });
    const timer = setTimeoutImpl(() => {
      try { child.kill('SIGTERM'); } catch {}
      settlePending(`${action} timed out waiting for the admin confirmation on the PC.`);
      onSettled?.(false);
    }, ELEVATION_TIMEOUT_MS);
    timer?.unref?.();
    pending = { action, startedAt: now(), timer, child };
    child.on('error', (error) => {
      settlePending(`${action} could not request elevation: ${error?.message || error}`);
      onSettled?.(false);
    });
    child.on('close', (code) => {
      if (!pending) return; // timeout already settled it
      if (code === 0) {
        settlePending(null);
        onSettled?.(true);
      } else {
        // 1 from Start-Process usually means the UAC prompt was declined.
        const detail = normalizeText(stderr).split('\n')[0] || `exit code ${code}`;
        settlePending(`${action} was not confirmed (${detail}). Run the command below from an elevated shell instead.`);
        onSettled?.(false);
      }
    });
  }

  async function requestEnable() {
    if (!supported) {
      throw new Error('Windows boot autostart is only available on Windows.');
    }
    if (spawnsDisabled()) {
      throw new Error('Windows boot autostart is disabled on this relay (CLI spawns are off).');
    }
    if (pending) {
      return { ...(await getState()), accepted: false };
    }
    lastError = null;
    writeFileAtomic(launcherPath(), buildBootLauncherScript({ packageRoot, nodePath, configPath, pathImpl }));
    const who = await execFileImpl('whoami', ['/user', '/fo', 'csv']);
    const sid = parseSidFromWhoami(who.stdout);
    if (!sid) {
      lastError = 'Could not determine the current user SID (whoami /user failed).';
      return { ...(await getState()), accepted: false };
    }
    writeFileAtomic(xmlPath(), encodeTaskXml(buildBootTaskXml({
      sid,
      launcherPath: launcherPath(),
      packageRoot: pathImpl.resolve(String(packageRoot)),
    })));
    writeFileAtomic(elevationScriptPath(), buildElevationScript({ action: 'enable', xmlPath: xmlPath() }));
    spawnElevated('enable', (ok) => {
      if (ok) {
        // Mutual exclusion: boot mode owns startup now, so the sign-in
        // entries (either name) must not race it at the next logon.
        const removed = removeStartupCmds();
        log(`enabled; removed ${removed} sign-in autostart entr${removed === 1 ? 'y' : 'ies'}`);
      } else {
        log(`enable did not complete: ${lastError}`);
      }
    });
    return { ...(await getState()), accepted: true };
  }

  async function requestDisable() {
    if (!supported) {
      throw new Error('Windows boot autostart is only available on Windows.');
    }
    if (spawnsDisabled()) {
      throw new Error('Windows boot autostart is disabled on this relay (CLI spawns are off).');
    }
    if (pending) {
      return { ...(await getState()), accepted: false };
    }
    lastError = null;
    writeFileAtomic(elevationScriptPath(), buildElevationScript({ action: 'disable' }));
    spawnElevated('disable', (ok) => {
      if (ok) {
        try {
          if (fsImpl.existsSync(launcherPath())) fsImpl.unlinkSync(launcherPath());
        } catch (error) {
          log(`could not remove launcher: ${error?.message || error}`);
        }
        log('disabled');
      } else {
        log(`disable did not complete: ${lastError}`);
      }
    });
    return { ...(await getState()), accepted: true };
  }

  return {
    getState,
    requestEnable,
    requestDisable,
  };
}
