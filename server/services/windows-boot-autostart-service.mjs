/**
 * "At system startup" autostart: a boot-trigger Scheduled Task running the
 * relay as the current user via S4U ("run whether user is logged on or not",
 * no stored password), headless, reachable before anyone signs in.
 *
 * The task's settings are a verbatim port of the hand-made task this design
 * was proven on (docs/plans/2026-09-02-windows-boot-autostart.md): boot
 * trigger +30s, no execution time limit, restart 5x/1min, StartWhenAvailable,
 * IgnoreNew. The task executes a generated launcher .cmd rather than node
 * directly, so a config-path change only regenerates a file — it never needs
 * the task re-registered (which would mean another elevation).
 *
 * Elevation is THE constraint here: registering or deleting a boot-trigger
 * task needs administrator rights and the relay runs unelevated. enable() and
 * disable() therefore spawn `Start-Process -Verb RunAs` around a generated
 * sweep script; the UAC prompt renders on the PC's physical desktop only, so
 * both report `pendingElevation` and the caller polls getState() until the
 * task appears/disappears (or shows `manualCommand` after a decline/timeout).
 * The elevated script does nothing but the schtasks calls — every file write
 * and cleanup stays in this unelevated process.
 */

export const BOOT_TASK_NAME = 'oar-relay';
// The hand-made pre-rebrand task. Recognized so the UI can offer migration,
// and deleted inside the same elevated sweep that registers the new name —
// one UAC covers the whole transition.
export const LEGACY_BOOT_TASK_NAME = 'copilot-remote-relay';
export const BOOT_LAUNCHER_FILENAME = 'oar-web-relay-launcher.cmd';
export const BOOT_TASK_XML_FILENAME = 'oar-relay-task.xml';
export const BOOT_ELEVATION_SCRIPT_FILENAME = 'oar-relay-elevate.ps1';
// Where a regenerated launcher keeps the one it replaced, when they differ.
export const BOOT_LAUNCHER_BACKUP_SUFFIX = '.bak';
const ELEVATION_TIMEOUT_MS = 120_000;
// Next to the launcher: a wait for TEMP and the data drive that ran out (see
// autostartWaitLines; AUTOSTART_WAIT_SECONDS is the limit).
export const BOOT_LAUNCHER_LOG_FILENAME = 'oar-web-relay-launcher.log';
// Each schtasks query; the settings page waits on two of them.
const QUERY_TIMEOUT_MS = 6_000;

function normalizeText(value) {
  return String(value == null ? '' : value).trim();
}

function escapeXml(value) {
  return String(value == null ? '' : value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

/**
 * The launcher the task executes. Same shape as the sign-in .cmd minus the
 * `title` line: a boot task runs in session 0 where no console is ever shown.
 * Like it, the launcher pins the config and the data and log folders `oar
 * start` uses, so both start the same relay.
 *
 * Node's folder goes at the end of PATH. The relay itself runs on the
 * absolute path below, but a boot task's PATH can lack the user's Node (a
 * version manager's folder, an entry that refers to an unexpanded variable),
 * and the CLIs and commands the workers start may call a bare `node`. At the
 * end it only matters when PATH has no Node of its own.
 *
 * Before Node starts it waits for %TEMP% and the data drive (autostartWaitLines),
 * logging a wait that ran out to BOOT_LAUNCHER_LOG_FILENAME beside it.
 */
const BOOT_LAUNCHER_HEADER = [
  '@echo off',
  'rem Generated by OAR settings (system-startup autostart). Regenerated on',
  'rem every settings change - do not edit by hand.',
];

function bootLauncherInputs({ packageRoot, nodePath, workingDirectory, pathImpl }) {
  if (!normalizeText(packageRoot)) {
    throw new Error('Windows boot autostart requires the package root.');
  }
  if (!normalizeText(nodePath)) {
    throw new Error('Windows boot autostart requires the Node.js executable path.');
  }
  const resolvedPackageRoot = pathImpl.resolve(String(packageRoot));
  return {
    serverPath: pathImpl.join(resolvedPackageRoot, 'server', 'server.js'),
    resolvedNodePath: pathImpl.resolve(nodePath),
    cwdTarget: normalizeText(workingDirectory)
      ? pathImpl.resolve(String(workingDirectory))
      : resolvedPackageRoot,
  };
}

function configLines(configPath, pathImpl) {
  return normalizeText(configPath)
    ? [`set "COPILOT_WEB_RELAY_CONFIG=${escapeBatchValue(pathImpl.resolve(configPath))}"`]
    : [];
}

// 0.9.11 to 0.9.13's wait (%TEMP% only, 120 s), verbatim, so a refresh knows it.
const EARLIER_BOOT_TEMP_WAIT_LINES = [
  'if "%TEMP%"=="" goto oar_start',
  'set /a OAR_TEMP_WAIT=0',
  ':oar_wait_temp',
  'if exist "%TEMP%\\" goto oar_start',
  'if %OAR_TEMP_WAIT% geq 120 goto oar_temp_missing',
  '"%SystemRoot%\\System32\\ping.exe" -n 2 127.0.0.1 >nul',
  'set /a OAR_TEMP_WAIT+=1',
  'goto oar_wait_temp',
  ':oar_temp_missing',
  `echo [%DATE% %TIME%] "%TEMP%" still missing after 120 s; starting the relay anyway.>>"%~dp0${BOOT_LAUNCHER_LOG_FILENAME}"`,
  ':oar_start',
  'set "OAR_TEMP_WAIT="',
];

// The boot launcher's lines after the padding, with the wait and the Node
// line's ending given (see launcherNodeLine).
function bootBodyLines({ resolvedNodePath, serverPath, cwdTarget, configPath, dataDir, logDir, pathImpl, waitLines, nodeLineOptions = {} }) {
  return [
    `set "PATH=%PATH%;${escapeBatchValue(pathImpl.dirname(resolvedNodePath))}"`,
    ...configLines(configPath, pathImpl),
    ...stateDirLines({ dataDir, logDir, pathImpl }),
    ...waitLines,
    `cd /d "${escapeBatchValue(cwdTarget)}"`,
    launcherNodeLine(resolvedNodePath, serverPath, nodeLineOptions),
  ];
}

export function buildBootLauncherScript({
  packageRoot,
  nodePath = process.execPath,
  configPath = '',
  dataDir = '',
  logDir = '',
  // Where the relay process lives, NOT where its code lives: on Windows a
  // process pins its cwd, and self-update must be able to replace the package
  // directory. Callers pass the OAR state root; the package-root default only
  // serves builders that predate self-update.
  workingDirectory = '',
  // Size of the file this one replaces (see buildLauncherFile).
  coverBytes = 0,
  pathImpl = path,
} = {}) {
  const { serverPath, resolvedNodePath, cwdTarget } = bootLauncherInputs({ packageRoot, nodePath, workingDirectory, pathImpl });
  return buildLauncherFile({
    headerLines: BOOT_LAUNCHER_HEADER,
    bodyLines: bootBodyLines({
      resolvedNodePath,
      serverPath,
      cwdTarget,
      configPath,
      dataDir,
      logDir,
      pathImpl,
      waitLines: autostartWaitLines({ dataDir, logTarget: `"%~dp0${BOOT_LAUNCHER_LOG_FILENAME}"`, pathImpl }),
    }),
    coverBytes,
  });
}

/**
 * The launchers earlier versions generated, newest first: the padded one
 * before 0.9.14 shipped (120 s TEMP wait, `& exit /b`; needs `dataDir` and
 * `logDir`), 0.9.11 to 0.9.13, then 0.9.2 to 0.9.10.
 */
export function buildEarlierBootLauncherScripts({
  packageRoot,
  nodePath,
  configPath = '',
  dataDir = '',
  logDir = '',
  workingDirectory = '',
  pathImpl = path,
} = {}) {
  const { serverPath, resolvedNodePath, cwdTarget } = bootLauncherInputs({ packageRoot, nodePath, workingDirectory, pathImpl });
  const nodeLine = `"${escapeBatchValue(resolvedNodePath)}" "${escapeBatchValue(serverPath)}"`;
  const cdLine = `cd /d "${escapeBatchValue(cwdTarget)}"`;
  return [
    buildLauncherFile({
      headerLines: BOOT_LAUNCHER_HEADER,
      bodyLines: bootBodyLines({
        resolvedNodePath,
        serverPath,
        cwdTarget,
        configPath,
        dataDir,
        logDir,
        pathImpl,
        waitLines: EARLIER_BOOT_TEMP_WAIT_LINES,
        nodeLineOptions: { ending: 'exit /b' },
      }),
    }),
    [
      ...BOOT_LAUNCHER_HEADER,
      `set "PATH=%PATH%;${escapeBatchValue(pathImpl.dirname(resolvedNodePath))}"`,
      ...configLines(configPath, pathImpl),
      ...EARLIER_BOOT_TEMP_WAIT_LINES,
      cdLine,
      nodeLine,
      '',
    ].join('\r\n'),
    [...BOOT_LAUNCHER_HEADER, ...configLines(configPath, pathImpl), cdLine, nodeLine, ''].join('\r\n'),
  ];
}

function unescapeXml(value) {
  return String(value)
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&');
}

/**
 * Task Scheduler XML, settings ported verbatim from the proven manual task.
 * The S4U principal is registered by SID, not account name: a by-name
 * principal breaks if the user is renamed, a SID does not.
 */
export function buildBootTaskXml({
  sid,
  launcherPath,
  packageRoot,
  // See buildBootLauncherScript: the task's cwd must survive a self-update
  // replacing the package directory, so callers pass the OAR state root.
  workingDirectory = '',
  description = 'Starts the OAR web relay at system startup (S4U, no logon required). Managed by OAR settings.',
} = {}) {
  if (!/^S-1-[\d-]+$/.test(normalizeText(sid))) {
    throw new Error(`Windows boot autostart requires the current user's SID (got: ${JSON.stringify(sid)}).`);
  }
  if (!normalizeText(launcherPath)) {
    throw new Error('Windows boot autostart requires the launcher path.');
  }
  if (!normalizeText(packageRoot)) {
    throw new Error('Windows boot autostart requires the package root.');
  }
  return [
    '<?xml version="1.0" encoding="UTF-16"?>',
    '<Task version="1.3" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">',
    '  <RegistrationInfo>',
    `    <Description>${escapeXml(description)}</Description>`,
    `    <URI>\\${BOOT_TASK_NAME}</URI>`,
    '  </RegistrationInfo>',
    '  <Principals>',
    '    <Principal id="Author">',
    `      <UserId>${escapeXml(normalizeText(sid))}</UserId>`,
    '      <LogonType>S4U</LogonType>',
    '    </Principal>',
    '  </Principals>',
    '  <Settings>',
    '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>',
    '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>',
    '    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>',
    '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>',
    '    <RestartOnFailure>',
    '      <Count>5</Count>',
    '      <Interval>PT1M</Interval>',
    '    </RestartOnFailure>',
    '    <StartWhenAvailable>true</StartWhenAvailable>',
    '    <UseUnifiedSchedulingEngine>true</UseUnifiedSchedulingEngine>',
    '  </Settings>',
    '  <Triggers>',
    '    <BootTrigger>',
    '      <Delay>PT30S</Delay>',
    '    </BootTrigger>',
    '  </Triggers>',
    '  <Actions Context="Author">',
    '    <Exec>',
    '      <Command>C:\\Windows\\System32\\cmd.exe</Command>',
    `      <Arguments>/d /c "${escapeXml(launcherPath)}"</Arguments>`,
    `      <WorkingDirectory>${escapeXml(normalizeText(workingDirectory) || packageRoot)}</WorkingDirectory>`,
    '    </Exec>',
    '  </Actions>',
    '</Task>',
    '',
  ].join('\r\n');
}

/**
 * schtasks rejects a UTF-8 file whose XML header declares UTF-16 (and the
 * header must declare UTF-16 for /create /xml) — so the bytes on disk are
 * UTF-16LE with a BOM, matching what `schtasks /query /xml` itself exports.
 */
export function encodeTaskXml(xml) {
  return Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(String(xml), 'utf16le')]);
}

/** Minimal field scrape of a task's exported XML; no XML parser dependency. */
export function parseTaskXml(xmlText) {
  const text = String(xmlText == null ? '' : xmlText);
  const grab = (tag) => {
    const match = text.match(new RegExp(`<${tag}>([^<]*)</${tag}>`));
    return match ? unescapeXml(match[1]).trim() : null;
  };
  const bootTrigger = text.match(/<BootTrigger>([\s\S]*?)<\/BootTrigger>/);
  const bootDelay = bootTrigger ? (bootTrigger[1].match(/<Delay>([^<]*)<\/Delay>/)?.[1]?.trim() || null) : null;
  return {
    command: grab('Command'),
    argumentsLine: grab('Arguments'),
    workingDirectory: grab('WorkingDirectory'),
    logonType: grab('LogonType'),
    userId: grab('UserId'),
    hasBootTrigger: Boolean(bootTrigger),
    bootDelay,
  };
}

function sameText(a, b) {
  return normalizeText(a).toLowerCase() === normalizeText(b).toLowerCase();
}

// Windows paths: no case, either slash, no trailing separator.
function samePath(a, b) {
  const normalize = (value) => normalizeText(value).replaceAll('/', '\\').replace(/\\+$/, '').toLowerCase();
  return normalize(a) === normalize(b);
}

/**
 * How a task that runs our launcher differs from the one buildBootTaskXml
 * registers, as short names (empty when it does not). Only what the generated
 * XML sets is compared: Task Scheduler adds its own defaults on export, and
 * the run level, for one, is not set by OAR.
 */
export function describeTaskCustomisations(xmlText, { launcherPath, workingDirectory } = {}) {
  const parsed = parseTaskXml(xmlText);
  const differences = [];
  if (!sameText(parsed.command, 'C:\\Windows\\System32\\cmd.exe')
    || normalizeText(parsed.argumentsLine).replace(/\s+/g, ' ').toLowerCase()
      !== `/d /c "${normalizeText(launcherPath)}"`.toLowerCase()) {
    differences.push('action');
  }
  if (normalizeText(workingDirectory) && !samePath(parsed.workingDirectory, workingDirectory)) {
    differences.push('working-directory');
  }
  if (!sameText(parsed.logonType, 'S4U')) differences.push('logon-type');
  if (!parsed.hasBootTrigger) differences.push('trigger');
  else if (!sameText(parsed.bootDelay, 'PT30S')) differences.push('boot-delay');
  return differences;
}

// Shared with the sign-in entry; still exported from here for its callers.
export { launcherScriptsMatch };

/**
 * Ours or someone else's? A task counts as ours when its action runs our
 * launcher path; anything else under our name is `foreign` and the UI offers
 * an explicit "Replace", never a silent overwrite.
 */
export function classifyTaskXml(xmlText, { launcherPath } = {}) {
  const parsed = parseTaskXml(xmlText);
  const needle = normalizeText(launcherPath).toLowerCase();
  if (needle && String(parsed.argumentsLine || '').toLowerCase().includes(needle)) {
    return 'ready';
  }
  return 'foreign';
}

/**
 * The elevated sweep. Everything the admin token is actually needed for —
 * and nothing else — in one script, so one UAC covers the whole transition
 * out of any mixed state (legacy-named task, hand-made task, fresh install).
 */
export function buildElevationScript({ action, xmlPath, schtasksPath = 'schtasks' } = {}) {
  // PowerShell runs a quoted path only behind the call operator.
  const schtasks = /[\\/]/.test(schtasksPath) ? `& "${schtasksPath}"` : schtasksPath;
  if (action === 'enable') {
    if (!normalizeText(xmlPath)) {
      throw new Error('The enable sweep needs the task XML path.');
    }
    return [
      `${schtasks} /delete /tn "${LEGACY_BOOT_TASK_NAME}" /f 2>$null`,
      `${schtasks} /delete /tn "${BOOT_TASK_NAME}" /f 2>$null`,
      `${schtasks} /create /tn "${BOOT_TASK_NAME}" /xml "${xmlPath}"`,
      'exit $LASTEXITCODE',
      '',
    ].join('\r\n');
  }
  if (action === 'disable') {
    return [
      `${schtasks} /delete /tn "${BOOT_TASK_NAME}" /f 2>$null`,
      `${schtasks} /delete /tn "${LEGACY_BOOT_TASK_NAME}" /f 2>$null`,
      'exit 0',
      '',
    ].join('\r\n');
  }
  throw new Error(`Unknown elevation action: ${JSON.stringify(action)}`);
}

/** `whoami /user /fo csv` → the current user's SID. */
export function parseSidFromWhoami(stdout) {
  const match = String(stdout || '').match(/"(S-1-[\d-]+)"/);
  return match ? match[1] : null;
}

// `startError` is set when the program did not run at all (not found, timed
// out): unlike an exit code, that says nothing about the task.
function defaultExecFileImpl(file, args) {
  return new Promise((resolve) => {
    execFile(file, args, { windowsHide: true, timeout: QUERY_TIMEOUT_MS }, (error, stdout, stderr) => {
      const exitCode = typeof error?.code === 'number' ? error.code : null;
      resolve({
        code: error ? (exitCode ?? 1) : 0,
        stdout: String(stdout || ''),
        stderr: String(stderr || ''),
        startError: error && (exitCode === null || error.killed)
          ? describeExecError(error)
          : null,
      });
    });
  });
}

export function createWindowsBootAutostartService({
  platform = process.platform,
  env = process.env,
  packageRoot,
  nodePath = process.execPath,
  configPath = '',
  fsImpl = fs,
  pathImpl = path,
  execFileImpl = defaultExecFileImpl,
  spawnImpl = spawn,
  setTimeoutImpl = setTimeout,
  clearTimeoutImpl = clearTimeout,
  now = () => Date.now(),
  logger = console,
  // Full path of a Windows program (schtasks, whoami, powershell).
  systemToolPath = (name) => windowsSystemToolPath(name, { env }),
} = {}) {
  const supported = platform === 'win32';
  // One elevation in flight at a time; getState() reports it and the
  // completion callback resolves it.
  let pending = null; // { action, startedAt, timer, child }
  let lastError = null;
  // The launcher an enable replaced, kept beside it (see requestEnable).
  let launcherBackupPath = null;

  const oarRoot = () => resolveOarRoot(env, platform);
  const launcherPath = () => pathImpl.join(oarRoot(), BOOT_LAUNCHER_FILENAME);
  const xmlPath = () => pathImpl.join(oarRoot(), BOOT_TASK_XML_FILENAME);
  const serverPath = () => pathImpl.join(pathImpl.resolve(String(packageRoot || '')), 'server', 'server.js');
  const elevationScriptPath = () => pathImpl.join(oarRoot(), BOOT_ELEVATION_SCRIPT_FILENAME);

  function log(message) {
    try { logger?.log?.(`[boot-autostart] ${message}`); } catch {}
  }

  const tool = (name) => systemToolPath(name);

  /**
   * The task's XML, null when there is no such task, or `{ readError }` when
   * schtasks itself could not run: that says nothing about the task, so it
   * must not read as "missing".
   */
  async function queryTaskXml(taskName) {
    let result;
    try {
      result = await execFileImpl(tool('schtasks'), ['/query', '/tn', taskName, '/xml']);
    } catch (error) {
      result = { code: 1, stdout: '', stderr: '', startError: describeExecError(error) };
    }
    if (result?.startError) {
      log(`schtasks /query ${taskName} did not run: ${result.startError}; ${describeSpawnEnvironment(env, platform)}`);
      // The details stay in the log (they can name folders on the host).
      return { readError: 'schtasks could not be run; the relay log has the details.' };
    }
    return result?.code === 0 ? result.stdout : null;
  }

  function readLauncher() {
    try {
      return fsImpl.existsSync(launcherPath()) ? String(fsImpl.readFileSync(launcherPath(), 'utf8')) : null;
    } catch {
      return null;
    }
  }

  function generatedLauncher({ stateDirs, coverBytes = 0, nodePathOverride = null } = {}) {
    return buildBootLauncherScript({
      packageRoot,
      nodePath: nodePathOverride || nodePath,
      configPath,
      ...(stateDirs || resolveRelayStateDirs({ packageRoot, env, platform, fsImpl, pathImpl })),
      workingDirectory: oarRoot(),
      coverBytes,
      pathImpl,
    });
  }

  /**
   * Brings a launcher an earlier version wrote (see
   * buildEarlierBootLauncherScripts) up to date; the relay calls this once it
   * runs. The task runs the launcher file, so this needs no elevation. Only a
   * launcher exactly as that version generated it for this install and its
   * config is rewritten, keeping the Node it runs; an edited one stays (it
   * reads as customised, and enabling again replaces it, keeping a copy). It
   * pins only the install's own folders (resolveLayoutStateDirs). True when
   * it rewrote the launcher.
   */
  // `onEarlierForm`: the earlier form found (`pinnedData` false: package database).
  function refreshInstalledLauncher({ onEarlierForm } = {}) {
    if (!supported || spawnsDisabled()) return false;
    const stateDirs = resolveLayoutStateDirs({ packageRoot, env, platform, fsImpl, pathImpl });
    if (!stateDirs) return false;
    const current = readLauncher();
    if (current === null) return false;
    const launcherNodePath = readLauncherNodePath(current, serverPath());
    if (!launcherNodePath) return false;
    const earlier = buildEarlierBootLauncherScripts({
      packageRoot, nodePath: launcherNodePath, configPath, ...stateDirs, workingDirectory: oarRoot(), pathImpl,
    });
    const matched = earlier.find((script) => launcherScriptsMatch(current, script, { ignoreCase: true }));
    if (!matched) return false;
    onEarlierForm?.({ path: launcherPath(), pinnedData: matched.includes('COPILOT_WEB_RELAY_DATA_DIR') });
    writeFileAtomic(launcherPath(), generatedLauncher({
      stateDirs,
      nodePathOverride: launcherNodePath,
      coverBytes: Buffer.byteLength(current, 'utf8'),
    }));
    return true;
  }

  /** What differs from the generated task and launcher, for a task that runs our launcher. */
  function customisationsOf(xmlText) {
    const differences = describeTaskCustomisations(xmlText, {
      launcherPath: launcherPath(),
      workingDirectory: oarRoot(),
    });
    const launcher = readLauncher();
    if (launcher === null) differences.push('launcher-missing');
    else {
      try {
        // Against the Node the launcher runs, as the repair keeps it: a moved
        // Node is no customisation.
        const ownNodePath = readLauncherNodePath(launcher, serverPath());
        if (!launcherScriptsMatch(launcher, generatedLauncher({ nodePathOverride: ownNodePath }))) {
          differences.push('launcher');
        }
      } catch {}
    }
    return differences;
  }

  function startupCmdPaths() {
    const dir = resolveWindowsStartupDirectory(env, pathImpl);
    return [
      pathImpl.join(dir, WINDOWS_AUTOSTART_FILENAME),
      pathImpl.join(dir, LEGACY_WINDOWS_AUTOSTART_FILENAME),
    ];
  }

  function removeStartupCmds() {
    let removed = 0;
    for (const target of startupCmdPaths()) {
      try {
        if (fsImpl.existsSync(target)) {
          fsImpl.unlinkSync(target);
          removed += 1;
        }
      } catch (error) {
        log(`could not remove ${target}: ${error?.message || error}`);
      }
    }
    return removed;
  }

  function manualCommandFor(action) {
    return action === 'disable'
      ? `schtasks /delete /tn "${BOOT_TASK_NAME}" /f`
      : `schtasks /create /tn "${BOOT_TASK_NAME}" /xml "${xmlPath()}" /f`;
  }

  function spawnsDisabled() {
    // The e2e harness's kill switch. schtasks is not a provider CLI, but the
    // point is identical: an isolated relay must not read (let alone mutate)
    // host machine state.
    return Boolean(normalizeText(env?.COPILOT_WEB_RELAY_DISABLE_CLI_SPAWN));
  }

  async function getState() {
    if (!supported) {
      return { supported: false, platform };
    }
    if (spawnsDisabled()) {
      return {
        supported: true,
        platform,
        taskStatus: 'unknown',
        taskName: BOOT_TASK_NAME,
        legacyTaskPresent: false,
        launcherPath: null,
        pendingElevation: null,
        lastError: null,
        manualCommand: manualCommandFor('enable'),
      };
    }
    const ownXml = await queryTaskXml(BOOT_TASK_NAME);
    const legacyXml = await queryTaskXml(LEGACY_BOOT_TASK_NAME);
    const readError = ownXml?.readError || null;
    const legacyKnown = typeof legacyXml === 'string';
    let taskStatus;
    if (readError) taskStatus = 'unknown';
    else if (ownXml === null) taskStatus = legacyKnown ? 'legacy' : 'missing';
    else taskStatus = classifyTaskXml(ownXml, { launcherPath: launcherPath() });
    // A task that runs our launcher but is not quite the one OAR registers (no
    // boot delay, an edited launcher) still is boot mode; it is reported,
    // never failed on.
    const customisations = taskStatus === 'ready' ? customisationsOf(ownXml) : [];
    let launcherPresent = false;
    try { launcherPresent = fsImpl.existsSync(launcherPath()); } catch {}
    return {
      supported: true,
      platform,
      taskStatus,
      taskName: BOOT_TASK_NAME,
      legacyTaskPresent: legacyKnown,
      launcherPath: launcherPresent ? launcherPath() : null,
      customised: customisations.length > 0,
      customisations,
      launcherBackupPath,
      readError,
      pendingElevation: pending ? pending.action : null,
      lastError,
      manualCommand: manualCommandFor(pending?.action || 'enable'),
    };
  }

  function writeFileAtomic(targetPath, contents) {
    fsImpl.mkdirSync(pathImpl.dirname(targetPath), { recursive: true });
    const temporaryPath = `${targetPath}.tmp`;
    fsImpl.writeFileSync(temporaryPath, contents);
    fsImpl.renameSync(temporaryPath, targetPath);
  }

  function settlePending(outcome) {
    if (!pending) return;
    if (pending.timer) clearTimeoutImpl(pending.timer);
    pending = null;
    lastError = outcome || null;
  }

  /**
   * The elevated child is powershell running Start-Process -Verb RunAs -Wait:
   * the outer process lives exactly as long as the UAC prompt plus the sweep
   * script, so its exit is the "elevation finished (or was declined)" signal.
   */
  function spawnElevated(action, onSettled) {
    const powershell = tool('powershell.exe');
    const child = spawnImpl(powershell, [
      '-NoProfile',
      '-NonInteractive',
      '-Command',
      [
        `$p = Start-Process -FilePath '${powershell.replaceAll("'", "''")}' -Verb RunAs -Wait -PassThru -WindowStyle Hidden -ArgumentList`,
        `'-NoProfile','-ExecutionPolicy','Bypass','-File','${elevationScriptPath()}'`,
        '; exit $p.ExitCode',
      ].join(' '),
    ], {
      stdio: ['ignore', 'ignore', 'pipe'],
      windowsHide: true,
    });
    let stderr = '';
    child.stderr?.on?.('data', (chunk) => { stderr = `${stderr}${chunk}`.slice(-2000); });
    const timer = setTimeoutImpl(() => {
      try { child.kill('SIGTERM'); } catch {}
      settlePending(`${action} timed out waiting for the admin confirmation on the PC.`);
      onSettled?.(false);
    }, ELEVATION_TIMEOUT_MS);
    timer?.unref?.();
    pending = { action, startedAt: now(), timer, child };
    child.on('error', (error) => {
      settlePending(`${action} could not request elevation: ${error?.message || error}`);
      onSettled?.(false);
    });
    child.on('close', (code) => {
      if (!pending) return; // timeout already settled it
      if (code === 0) {
        settlePending(null);
        onSettled?.(true);
      } else {
        // 1 from Start-Process usually means the UAC prompt was declined.
        const detail = normalizeText(stderr).split('\n')[0] || `exit code ${code}`;
        settlePending(`${action} was not confirmed (${detail}). Run the command below from an elevated shell instead.`);
        onSettled?.(false);
      }
    });
  }

  async function requestEnable() {
    if (!supported) {
      throw new Error('Windows boot autostart is only available on Windows.');
    }
    if (spawnsDisabled()) {
      throw new Error('Windows boot autostart is disabled on this relay (CLI spawns are off).');
    }
    if (pending) {
      return { ...(await getState()), accepted: false };
    }
    lastError = null;
    const launcher = generatedLauncher();
    const previous = readLauncher();
    if (previous !== null && !launcherScriptsMatch(previous, launcher)) {
      // An edited (or older) launcher is replaced, but kept: one copy, the
      // latest replaced one.
      const backupPath = `${launcherPath()}${BOOT_LAUNCHER_BACKUP_SUFFIX}`;
      try {
        fsImpl.writeFileSync(backupPath, previous);
        launcherBackupPath = backupPath;
        log(`the launcher differed from the generated one; saved it as ${backupPath}`);
      } catch (error) {
        log(`could not save the current launcher as ${backupPath}: ${error?.message || error}`);
        lastError = 'Could not keep a copy of the current launcher next to it, so it was not replaced; the relay log has the details.';
        return { ...(await getState()), accepted: false };
      }
    }
    writeFileAtomic(launcherPath(), generatedLauncher({ coverBytes: previous === null ? 0 : Buffer.byteLength(previous, 'utf8') }));
    const who = await execFileImpl(tool('whoami'), ['/user', '/fo', 'csv']);
    const sid = parseSidFromWhoami(who.stdout);
    if (!sid) {
      lastError = 'Could not determine the current user SID (whoami /user failed).';
      return { ...(await getState()), accepted: false };
    }
    writeFileAtomic(xmlPath(), encodeTaskXml(buildBootTaskXml({
      sid,
      launcherPath: launcherPath(),
      packageRoot: pathImpl.resolve(String(packageRoot)),
      workingDirectory: oarRoot(),
    })));
    writeFileAtomic(elevationScriptPath(), buildElevationScript({ action: 'enable', xmlPath: xmlPath(), schtasksPath: tool('schtasks') }));
    spawnElevated('enable', (ok) => {
      if (ok) {
        // Mutual exclusion: boot mode owns startup now, so the sign-in
        // entries (either name) must not race it at the next logon.
        const removed = removeStartupCmds();
        log(`enabled; removed ${removed} sign-in autostart entr${removed === 1 ? 'y' : 'ies'}`);
      } else {
        log(`enable did not complete: ${lastError}`);
      }
    });
    return { ...(await getState()), accepted: true };
  }

  async function requestDisable() {
    if (!supported) {
      throw new Error('Windows boot autostart is only available on Windows.');
    }
    if (spawnsDisabled()) {
      throw new Error('Windows boot autostart is disabled on this relay (CLI spawns are off).');
    }
    if (pending) {
      return { ...(await getState()), accepted: false };
    }
    lastError = null;
    launcherBackupPath = null;
    writeFileAtomic(elevationScriptPath(), buildElevationScript({ action: 'disable', schtasksPath: tool('schtasks') }));
    spawnElevated('disable', (ok) => {
      if (ok) {
        try {
          if (fsImpl.existsSync(launcherPath())) fsImpl.unlinkSync(launcherPath());
        } catch (error) {
          log(`could not remove launcher: ${error?.message || error}`);
        }
        log('disabled');
      } else {
        log(`disable did not complete: ${lastError}`);
      }
    });
    return { ...(await getState()), accepted: true };
  }

  return {
    getState,
    requestEnable,
    requestDisable,
    refreshInstalledLauncher,
  };
}
