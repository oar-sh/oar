function normalizeText(value) {
  return String(value == null ? '' : value).trim();
}

function escapeXml(value) {
  return String(value == null ? '' : value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

/**
 * The launcher the task executes. Same shape as the sign-in .cmd minus the
 * `title` line: a boot task runs in session 0 where no console is ever shown.
 * Like it, the launcher pins the config and the data and log folders `oar
 * start` uses, so both start the same relay.
 *
 * Node's folder goes at the end of PATH. The relay itself runs on the
 * absolute path below, but a boot task's PATH can lack the user's Node (a
 * version manager's folder, an entry that refers to an unexpanded variable),
 * and the CLIs and commands the workers start may call a bare `node`. At the
 * end it only matters when PATH has no Node of its own.
 *
 * Before Node starts it waits for %TEMP% and the data drive (autostartWaitLines),
 * logging a wait that ran out to BOOT_LAUNCHER_LOG_FILENAME beside it.
 */
const BOOT_LAUNCHER_HEADER = [
  '@echo off',
  'rem Generated by OAR settings (system-startup autostart). Regenerated on',
  'rem every settings change - do not edit by hand.',
];

function bootLauncherInputs({ packageRoot, nodePath, workingDirectory, pathImpl }) {
  if (!normalizeText(packageRoot)) {
    throw new Error('Windows boot autostart requires the package root.');
  }
  if (!normalizeText(nodePath)) {
    throw new Error('Windows boot autostart requires the Node.js executable path.');
  }
  const resolvedPackageRoot = pathImpl.resolve(String(packageRoot));
  return {
    serverPath: pathImpl.join(resolvedPackageRoot, 'server', 'server.js'),
    resolvedNodePath: pathImpl.resolve(nodePath),
    cwdTarget: normalizeText(workingDirectory)
      ? pathImpl.resolve(String(workingDirectory))
      : resolvedPackageRoot,
  };
}

function configLines(configPath, pathImpl) {
  return normalizeText(configPath)
    ? [`set "COPILOT_WEB_RELAY_CONFIG=${escapeBatchValue(pathImpl.resolve(configPath))}"`]
    : [];
}

// 0.9.11 to 0.9.13's wait (%TEMP% only, 120 s), verbatim, so a refresh knows it.
const EARLIER_BOOT_TEMP_WAIT_LINES = [
  'if "%TEMP%"=="" goto oar_start',
  'set /a OAR_TEMP_WAIT=0',
  ':oar_wait_temp',
  'if exist "%TEMP%\\" goto oar_start',
  'if %OAR_TEMP_WAIT% geq 120 goto oar_temp_missing',
  '"%SystemRoot%\\System32\\ping.exe" -n 2 127.0.0.1 >nul',
  'set /a OAR_TEMP_WAIT+=1',
  'goto oar_wait_temp',
  ':oar_temp_missing',
  `echo [%DATE% %TIME%] "%TEMP%" still missing after 120 s; starting the relay anyway.>>"%~dp0${BOOT_LAUNCHER_LOG_FILENAME}"`,
  ':oar_start',
  'set "OAR_TEMP_WAIT="',
];

// The boot launcher's lines after the padding, with the wait and the Node
// line's ending given (see launcherNodeLine).
function bootBodyLines({ resolvedNodePath, serverPath, cwdTarget, configPath, dataDir, logDir, pathImpl, waitLines, nodeLineOptions = {} }) {
  return [
    `set "PATH=%PATH%;${escapeBatchValue(pathImpl.dirname(resolvedNodePath))}"`,
    ...configLines(configPath, pathImpl),
    ...stateDirLines({ dataDir, logDir, pathImpl }),
    ...waitLines,
    `cd /d "${escapeBatchValue(cwdTarget)}"`,
    launcherNodeLine(resolvedNodePath, serverPath, nodeLineOptions),
  ];
}

export function buildBootLauncherScript({
  packageRoot,
  nodePath = process.execPath,
  configPath = '',
  dataDir = '',
  logDir = '',
  // Where the relay process lives, NOT where its code lives: on Windows a
  // process pins its cwd, and self-update must be able to replace the package
  // directory. Callers pass the OAR state root; the package-root default only
  // serves builders that predate self-update.
  workingDirectory = '',
  // Size of the file this one replaces (see buildLauncherFile).
  coverBytes = 0,
  pathImpl = path,
} = {}) {
  const { serverPath, resolvedNodePath, cwdTarget } = bootLauncherInputs({ packageRoot, nodePath, workingDirectory, pathImpl });
  return buildLauncherFile({
    headerLines: BOOT_LAUNCHER_HEADER,
    bodyLines: bootBodyLines({
      resolvedNodePath,
      serverPath,
      cwdTarget,
      configPath,
      dataDir,
      logDir,
      pathImpl,
      waitLines: autostartWaitLines({ dataDir, logTarget: `"%~dp0${BOOT_LAUNCHER_LOG_FILENAME}"`, pathImpl }),
    }),
    coverBytes,
  });
}

